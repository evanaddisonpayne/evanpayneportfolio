// Builds public/map/i18n.js (window.MAP_I18N) for the travel map from content/map/<lang>.json.
// English stays in public/travel-map.html itself. Run after editing a map translation:
//   node scripts/build-map-i18n.mjs
import { readFileSync, writeFileSync } from "node:fs";

const langs = ["fr", "de"];
const out = {};
for (const l of langs) {
  const { _note, ...strings } = JSON.parse(readFileSync(new URL(`../content/map/${l}.json`, import.meta.url), "utf8"));
  out[l] = strings;
}
const js = `// Generated by scripts/build-map-i18n.mjs from content/map/*.json. Don't edit by hand.\nwindow.MAP_I18N = ${JSON.stringify(out)};\n`;
writeFileSync(new URL("../public/map/i18n.js", import.meta.url), js);
console.log(`public/map/i18n.js: ${langs.join(", ")} (${js.length} bytes)`);
